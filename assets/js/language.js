const originalText = new WeakMap();
const originalAttributes = new WeakMap();
const translatableAttributes = ["aria-label", "placeholder", "title"];
const originalTitle = document.title;

const normalizedText = (value) => value.trim().replace(/\s+/g, " ");

const translateValue = (source) => {
  const key = normalizedText(source);
  if (osoSenseTranslations[key]) return osoSenseTranslations[key];

  const githubLabel = key.match(/^GitHub de (.+), enlace próximamente$/);
  if (githubLabel) return `GitHub for ${githubLabel[1]}, link coming soon`;

  return source;
};

const translatePage = (language) => {
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  let node;

  while ((node = walker.nextNode())) {
    if (!originalText.has(node)) originalText.set(node, node.nodeValue);
    const source = originalText.get(node);
    const key = normalizedText(source);
    if (!key) continue;

    if (language === "en" && translateValue(key) !== key) {
      const leading = source.match(/^\s*/)?.[0] ?? "";
      const trailing = source.match(/\s*$/)?.[0] ?? "";
      node.nodeValue = `${leading}${translateValue(key)}${trailing}`;
    } else {
      node.nodeValue = source;
    }
  }

  document.querySelectorAll("*").forEach((element) => {
    if (!originalAttributes.has(element)) {
      const values = {};
      translatableAttributes.forEach((attribute) => {
        if (element.hasAttribute(attribute)) values[attribute] = element.getAttribute(attribute);
      });
      originalAttributes.set(element, values);
    }

    const values = originalAttributes.get(element);
    Object.entries(values).forEach(([attribute, source]) => {
      const key = normalizedText(source);
      element.setAttribute(attribute, language === "en" ? translateValue(source) : source);
    });
  });

  document.documentElement.lang = language;
  document.title =
    language === "en" && osoSenseTranslations[originalTitle]
      ? osoSenseTranslations[originalTitle]
      : originalTitle;
  document.querySelectorAll("[data-language]").forEach((button) => {
    const active = button.dataset.language === language;
    button.classList.toggle("is-active", active);
    button.setAttribute("aria-pressed", String(active));
  });
  const menuToggle = document.querySelector(".mobile-menu-toggle");
  if (menuToggle) {
    const menuOpen = menuToggle.getAttribute("aria-expanded") === "true";
    menuToggle.setAttribute(
      "aria-label",
      language === "en"
        ? menuOpen
          ? "Close menu"
          : "Open menu"
        : menuOpen
          ? "Cerrar menú"
          : "Abrir menú",
    );
  }
  localStorage.setItem("ososense-language", language);
};

document.querySelectorAll("[data-language]").forEach((button) => {
  button.addEventListener("click", () => translatePage(button.dataset.language));
});

translatePage(localStorage.getItem("ososense-language") || "en");